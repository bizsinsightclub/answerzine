// 네 프롬프트(그룹·토플라인·Auto·항목)가 공유하는 해석 원칙
export const LENS = `[해석 원칙]
- 대괄호 안의 순위 변동·복수 진입·교차 등장은 코드가 지난 주와 대조해 계산한 사실이다. 추정하지 말고 사실로 다루라. 사실을 이유로 되풀이하지 마라 — "올라서 올랐다", "2위에서 1위가 됐다"는 해석이 아니다. 해석은 그 사실이 사람들의 어떤 선택의 이동인지 쓴다.
- "무슨 일이 있었나"가 아니라 "사람들의 선택이 어디로 옮겨갔나"를 본다. 사건은 잊혀도 태도의 이동은 남는다.
- 동기는 다음 축에서 고르되 축 이름을 문장에 노출하지 마라: 못 사게 될까 봐(마감·손실 회피) / 결말·규칙을 이미 아는 쪽을 고름(불확실성 회피) / 고르기를 순위·추천·유명인에게 맡김(판단 위임) / 다들 보니까, 대화에 끼려고(동조·소속) / 불안·위로·도피·분노의 배출구(정서 조절) / 색상·한정·인증으로 나를 표시함(자기표현·희소) / 편성·시간대·이미 익힌 것(습관·관성).
- 금지 표현: "팬덤이 강해서", "화제성", "입소문", "마케팅 효과", "인기가 많아서", "관심이 높아져", 세대론(MZ·Z세대·알파), 광고 상투어(진정성·공감·소통·새로운 패러다임·고객 중심), "경계가 무너진다"·"구조가 재편된다" 류의 근거 없는 선언, 없는 수치·점유율.
- 모든 포인트는 관찰(항목명을 직접 든다) + 동기 + 돈이 되는 지점, 셋을 다 갖춘다. 하나라도 없으면 그 포인트를 버린다.
- 근거가 약하면 그렇게 쓴다. 수동 스냅숏(무신사·KREAM·렉스몬드·Jente)이나 영어 표기(넷플릭스)는 "이 데이터만으로는 가릴 수 없다"고 밝힌다.
- 죽음·재난·범죄·정치 갈등이 얽힌 항목은 담담히 사실만 적고, 캠페인 소재로 제안하지 않는다. 특정 인물·집단을 조롱하지 않는다.
- 실시간 웹 검색을 하지 않는다. 학습된 배경지식만으로 판단하고, 실존하지 않는 출처나 통계를 지어내지 마라.`;

const line = (it, tag) => `${it.raw}${tag && tag[it.id] ? " " + tag[it.id] : ""}`;

// 그룹(음악/영화/OTT/…) 해석 — 카테고리 해석 카드 하나
export function buildGroupReadPrompt(week, groupLabel, cats, itemsByCat, tag) {
  const block = cats
    .map((c) => `[${c}]\n` + (itemsByCat.get(c) || []).map((it) => `- id:${it.id} ${it.rank}위 ${line(it, tag)}`).join("\n"))
    .join("\n\n");
  return `너는 광고대행사(제일기획) 기획자다. 아래는 ${week.label}(${week.start}~${week.end}) '${groupLabel}' 그룹의 카테고리별 TOP 10이다.

${block}

${LENS}

임무: 이 그룹에서 이번 주 무엇이 돈이 됐는지를 읽는다. 절차대로 생각하되 사고 과정은 출력하지 마라.
1. 이 그룹에서 통상 벌어지는 일(예: 신곡은 첫 주가 정점, TV는 편성이 순위를 만든다, 앱 상승률은 기한 있는 일이 지배한다)을 기준으로 세우고, 이번 주 목록이 그 기준에서 어디를 벗어났는지 찾아라. 벗어난 게 없으면 "안 움직였다"는 것 자체를 관찰로 삼아라.
2. 가장 강한 관찰 하나를 고른다. 두 카테고리 이상이면 둘을 가로지르는 관찰을 우선한다.
3. 그 관찰이 어떤 선택의 이동인지, 그래서 무엇이 돈이 되는지를 쓴다.

출력 필드:
- headline: 표 헤더와 해석 제목에 같이 쓰는 한 줄. 관찰을 담은 짧은 서술문 또는 명사구, 20자 내외. 물음표·느낌표 금지. 콘텐츠 제목 그대로 넣지 않기.
- summary: 관찰의 근거 2~3문장. 항목명과 순위를 직접 든다. 사실만.
- points: 3~5개. 각각 관찰+동기+돈이 되는 지점을 갖춘 완결된 1~2문장. 마지막 포인트는 브랜드가 이번 주 실제로 해볼 일 하나를 구체적 행동으로 쓴다(예: "상시 상품에도 마감일을 붙여라"). "무엇을 하나" 같은 물음이나 지시문을 그대로 옮기지 마라.
- keywords: 4~6개. 마케터가 기획서에 옮겨 쓸 개념어. 고유명사 금지, 공백 없이 2~7자, # 제외.
- anomalies: 이 그룹에서 설명이 필요한 항목 2~3개. itemId 는 위 목록의 id 값을 그대로. note 는 그 항목이 왜 거기 있는지를 동기 관점으로 한 문장 — 순위 변동 되풀이 금지.

설명이나 코드펜스 없이 JSON 객체 하나만 출력하라:
{"headline":"string","summary":"string","points":["string"],"keywords":["string"],"anomalies":[{"itemId":"string","note":"string"}]}`;
}

export function buildBundlePrompt(week, picks, tag) {
  const list = picks
    .map((p) => `- ${p.category}/${p.rank}위 ${line(p, tag)}${p.reason ? " — 헤드라인: " + p.reason.headline + " — 키워드: " + p.reason.keywords.slice(0, 8).join(", ") : ""}`)
    .join("\n");
  return `아래는 ${week.label} 기준 사용자가 고른 ${picks.length}개 항목이다.

[선택 항목]
${list}

${LENS}

다음 절차로 생각하되 사고 과정 자체는 출력하지 마라. 최종 결과만 낸다.
1. 이 카테고리들에서 통상 벌어지는 일과 비교해, 각 대상이 어떻게 벗어났는지 보라.
2. 공통 속성을 추상 개념 하나로 압축하라. 서로 다른 맥락이라도 억지로 연결하라.
3. 그 개념을 제목 한 줄로 패키징하라.

출력은 다음 두 필드만 낸다.
title: 단 하나의 강한 명사(또는 명사구) 한 줄. "OO 아니면 OO" 같은 이중 대비 구조나 완결된 문장을 쓰지 마라 — 2~8자 내외 명사 하나로 못박아라. 콘텐츠 제목을 그대로 넣지 마라.
content: 4~6문장. 반드시 아래 순서를 지켜라.
  (1) 관찰: 선택된 항목들에서 실제로 확인되는 공통 사실을 먼저 적는다. 항목명을 직접 들어, 각각이 그 카테고리의 통상 경로에서 어느 지점을 벗어났는지 짚는다.
  (2) 메커니즘: 그 사실들을 관통하는 소비자 행동의 원리를 설명한다. 사람들이 무엇을 아끼려 했는지(시간·탐색 비용·실패 위험), 무엇을 확인하려 했는지, 어떤 판단을 대신 맡겼는지를 짚는다.
  (3) 명명: 그래서 이 묶음을 왜 그 제목으로 부르는지 한 문장으로 못박는다.
  - 어투는 소비 트렌드 분석서에 가깝게. 단정적이되 과장하지 않는다. "개념적 추상화", "강제 연결", "프레임화" 같은 절차 용어를 쓰지 마라.

출력은 JSON만. {"title":"...", "content":"...", "keywords":["브랜드가 마케팅에 바로 써볼 수 있는 키워드 3~6개. 고유명사 금지, 소비자의 행동·정서·상황을 가리키는 개념어로. 공백 없이 2~7자, # 기호 제외"]} 세 키만.`;
}

// 연관 신호 Auto — 카테고리를 가로지르는 묶음 5개
export function buildAutoPrompt(week, allItems, prefs, facts, reads) {
  // 사용자가 카드에 남긴 좋아요/싫어요를 그대로 프롬프트에 넣어, 다음 묶음이 그 취향을
  // 따라가게 한다. 같은 조합을 반복하지 말라고 못박아 취향만 이어받게 한다.
  const p = prefs || { liked: [], disliked: [] };
  const likedBlock = p.liked.length
    ? "\n\n[사용자가 좋아한 묶음 — 이 관점·추상화 수준·문장 방식을 이어가라. 단, 같은 항목 조합을 다시 제안하지는 마라.]\n" +
      p.liked.slice(0, 6).map((x) => "- 제목: " + x.title + " / 항목: " + x.items + " / 요지: " + x.gist).join("\n")
    : "";
  const dislikedBlock = p.disliked.length
    ? "\n\n[사용자가 싫어한 묶음 — 이런 방향과 어투는 피하라.]\n" +
      p.disliked.slice(0, 4).map((x) => "- 제목: " + x.title + " / 항목: " + x.items + " / 요지: " + x.gist).join("\n")
    : "";
  const byId = new Map(allItems.map((it) => [it.id, it]));
  const tag = (facts && facts.tag) || {};
  const list = allItems.map((it) => `- id:${it.id} ${it.category}/${it.rank}위 ${line(it, tag)}`).join("\n");
  const echoes = ((facts && facts.echoes) || [])
    .map((ids) => "- " + ids.map((id) => byId.get(id)).filter(Boolean).map((it) => `${it.category} ${it.rank}위 ${it.title}`).join(" = "))
    .join("\n");
  const readLines = (reads || []).map((r) => `- ${r.group}: ${r.headline}`).join("\n");
  return (
    `아래는 ${week.label} 전체 카테고리 TOP 항목이다. 대괄호는 코드가 계산한 사실이다.

[전체 항목]
${list}

[표면 연결 — 이미 아는 사실. 다시 발견하지 마라]
${echoes || "- (교차 등장 없음)"}
${readLines ? "\n[그룹별 해석 헤드라인 — 이미 발행됨. 같은 말을 되풀이하지 마라]\n" + readLines : ""}

${LENS}

너의 임무는 서로 다른 카테고리를 가로지르는 조합을 스스로 5개 찾아 추천하는 것이다. 각 조합은 다음 기준을 따른다.
1. 서로 다른 카테고리를 최소 2개 이상 가로지를 것
2. 같은 IP·같은 인물 같은 표면 연결이 아니라, 그 항목들을 통과하는 동기가 같을 것. 표면 연결은 위에 이미 있다 — 그걸 다시 묶으면 실패다.
3. 카테고리 상식으로 예측 가능한 뻔한 묶음은 배제할 것
4. 조합당 항목 2~10개. 같은 동기가 여러 카테고리에 걸쳐 있으면 둘에서 멈추지 말고 근거가 되는 항목을 전부 넣어라. 다만 근거가 약한 항목을 수를 채우려고 넣지는 마라
5. 5개 조합은 서로 겹치지 않는 다른 동기를 다룰 것

정확히 5개의 조합을 JSON 배열로 출력하라. 각 원소 스키마:
{"itemIds":["존재하는 id만"],"title":"단 하나의 강한 명사(또는 명사구), 2~8자 내외, 콘텐츠 제목 그대로 넣지 않기","keywords":["키워드 3~6개 — 브랜드가 마케팅에 바로 쓸 수 있는 개념어. 고유명사 금지, 공백 없이 2~7자, # 기호 제외"],"content":"4~6문장. 가장 핵심적인 구절 1~2개를 **양쪽에 별표 두 개**로 감싸 강조하라. 문단당 최대 2개만, 구절 단위로. (1) 선택한 항목명을 직접 들어 각각이 통상 경로에서 벗어난 지점을 관찰로 적고 (2) 그것들을 관통하는 동기를 설명하고 (3) 그래서 이 제목으로 부른다고 한 문장으로 못박는다. 소비 트렌드 분석서 어투로, 추상적 수사 대신 사례와 해석으로 채운다. 절차 용어 금지"}

itemIds는 위 목록의 id 값만 정확히 그대로 사용하라. 설명이나 코드펜스 없이 JSON 배열만 출력하라.` +
    likedBlock +
    dislikedBlock
  );
}

export function likedBlockFor(liked) {
  return liked
    .slice(0, 8)
    .map((x, i) => `${i + 1}) 제목: ${x.title}\n   요지: ${x.gist}\n   묶인 항목: ${x.items}`)
    .join("\n");
}

export function ideaPrefBlock(ip) {
  const p = ip || { liked: [], disliked: [] };
  const up = p.liked.length
    ? "\n\n[사용자가 좋아한 실행 아이디어 — 이 결의 구체성·형식감을 이어가라. 같은 아이디어를 다시 내지는 마라.]\n" +
      p.liked.slice(0, 6).map((x) => "- " + x.title + " (" + x.items + ") : " + x.gist).join("\n")
    : "";
  const down = p.disliked.length
    ? "\n\n[사용자가 별로라고 한 아이디어 — 이런 방향은 피하라.]\n" +
      p.disliked.slice(0, 4).map((x) => "- " + x.title + " (" + x.items + ") : " + x.gist).join("\n")
    : "";
  return up + down;
}

